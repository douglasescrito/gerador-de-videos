function normalizedCommand(entry) {
  return {
    id: entry.id,
    // A família do comando. 72 comandos numa lista plana não respondem "o
    // que existe nessa área?"; agrupados, respondem.
    grupo: entry.grupo ?? "outros",
    options: [...entry.options],
    actionValues: entry.actionValues ? [...entry.actionValues] : [],
    protected: PROTECTED_COMMAND_IDS.includes(entry.id),
    // Nenhum comando exige confirmação de gasto: o projeto é local, a auth é
    // por cookie e não há custo medido por chamada. O campo permanece no
    // manifesto porque agentes o leem, e permanece sempre falso.
    confirmationRequired: false,
    conditionalConfirmations: (entry.conditionalConfirmations ?? []).map((rule) => ({ ...rule })),
    statusOverride: entry.statusOverride ?? null,
    capability: entry.capability ?? null,
    capabilityRequired: entry.capabilityRequired ?? false,
    replacement: entry.replacement ?? null,
    limitation: entry.limitation ?? null,
    summary: entry.summary,
    example: entry.example,
  };
}

export function listCommands() {
  return COMMAND_REGISTRY.map(normalizedCommand);
}

export function getCommand(id) {
  const entry = COMMAND_REGISTRY.find((candidate) => candidate.id === id);
  return entry ? normalizedCommand(entry) : null;
}

// Drop-in para o antigo literal `allowedOptions` de scripts/omni-cli.mjs:
// mesmo formato ({ [id]: Set<string> }), agora derivado do registry.
export function buildAllowedOptions() {
  return Object.fromEntries(COMMAND_REGISTRY.map((entry) => [entry.id, new Set(entry.options)]));
}
